/**
 * Bake the deploy tip into build/build-stamp.generated.js.
 * Sources, first match wins:
 *   GIT_SHA (wrangler deploy --var / Cos deploy var)
 *   WORKERS_CI_COMMIT_SHA (Workers Builds)
 *   CF_PAGES_COMMIT_SHA
 *   GITHUB_SHA
 *   git HEAD only when --from-git is passed (operator deploy.sh)
 * Never writes a hardcoded production SHA. Empty stays unset.
 */
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SHA_RE = /^[0-9a-f]{40}$/;

export function cleanSha(value) {
  const s = String(value ?? "").trim().toLowerCase();
  return SHA_RE.test(s) ? s : "";
}

export function resolveBuildStamp(env = {}, { fromGit = false, gitHead = "" } = {}) {
  const pairs = [
    ["GIT_SHA", "deploy_var"],
    ["WORKERS_CI_COMMIT_SHA", "workers_ci"],
    ["CF_PAGES_COMMIT_SHA", "cf_pages"],
    ["GITHUB_SHA", "github_sha"],
  ];
  for (const [name, source] of pairs) {
    const sha = cleanSha(env[name]);
    if (sha) return { sha, source };
  }
  if (fromGit) {
    const sha = cleanSha(gitHead);
    if (sha) return { sha, source: "git_head" };
  }
  return { sha: "", source: "unset" };
}

export function stampModuleSource(sha, source) {
  return `// Generated by scripts/write-build-stamp.mjs.
// Committed empty on purpose. Deploy rewrites this from the deploy stamp.
// Do not hardcode a production tip or version id.
export const BAKED_GIT_SHA = ${JSON.stringify(sha)};
export const BAKED_GIT_SHA_SOURCE = ${JSON.stringify(source)};
`;
}

export function stampFilePath() {
  return join(dirname(fileURLToPath(import.meta.url)), "../build/build-stamp.generated.js");
}

function readGitHead() {
  try {
    return execSync("git rev-parse HEAD", { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
}

export function writeBuildStamp(env = process.env, options = {}) {
  const fromGit = options.fromGit === true || process.argv.includes("--from-git");
  const gitHead = options.gitHead != null ? options.gitHead : fromGit ? readGitHead() : "";
  const { sha, source } = resolveBuildStamp(env, { fromGit, gitHead });
  const file = options.file || stampFilePath();
  const next = stampModuleSource(sha, source);
  let prev = "";
  try {
    prev = readFileSync(file, "utf8");
  } catch {
    prev = "";
  }
  if (prev !== next) writeFileSync(file, next);
  return { sha, source, file, wrote: prev !== next };
}

function isDirectRun() {
  const entry = process.argv[1];
  if (!entry) return false;
  try {
    return import.meta.url === pathToFileURL(entry).href;
  } catch {
    return false;
  }
}

if (isDirectRun()) {
  const result = writeBuildStamp();
  const shown = result.sha ? result.sha.slice(0, 12) + "…" : "(unset)";
  console.log("build stamp " + result.source + " " + shown + (result.wrote ? " wrote" : " unchanged"));
}
